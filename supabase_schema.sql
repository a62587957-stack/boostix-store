-- 1. جدول المستخدمين والمحافظ (Users)
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    balance NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (balance >= 0),
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    token TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. جدول المنتجات والباقات (Products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game TEXT NOT NULL,
    pack TEXT NOT NULL,
    price_usd NUMERIC(10, 2) NOT NULL CHECK (price_usd > 0),
    supplier_cost_usd NUMERIC(10, 2) NOT NULL DEFAULT 0.00 CHECK (supplier_cost_usd >= 0),
    sku TEXT NOT NULL,
    icon TEXT NOT NULL DEFAULT '🎮',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. جدول طلبات شحن المحافظ والإيداعات (Deposits)
CREATE TABLE IF NOT EXISTS public.deposits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    user_name TEXT NOT NULL,
    amount_usd NUMERIC(10, 2) NOT NULL CHECK (amount_usd > 0),
    method TEXT NOT NULL,
    tx_id TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL DEFAULT 'معلق' CHECK (status IN ('معلق', 'مقبول', 'مرفوض')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. جدول الطلبات (Orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    user_name TEXT NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    game TEXT NOT NULL,
    pack_name TEXT NOT NULL,
    sku TEXT NOT NULL,
    player_id TEXT NOT NULL,
    price_usd NUMERIC(10, 2) NOT NULL,
    supplier_cost_usd NUMERIC(10, 2) NOT NULL,
    admin_profit_usd NUMERIC(10, 2) NOT NULL,
    status TEXT NOT NULL DEFAULT 'قيد التنفيذ' CHECK (status IN ('قيد التنفيذ', 'مكتمل', 'مرفوض من المورد')),
    supplier_order_id TEXT,
    supplier_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.deposits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

